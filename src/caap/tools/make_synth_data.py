"""生成合成掌纹数据, 并把受害模型训练到可用精度, 用于在无真实数据时冒烟验证代码改动.

只验证代码路径是否走通, 产生的任何数值都不能写进论文.
"""
import argparse
import json
from pathlib import Path

import torch
import torch.nn.functional as F

from caap.data.data import PalmPrint
from caap.utils.net_factory import get_net

ARC_NETS = {"compnet", "ccnet", "co3net"}


def make_split(num_class, per_class, size=128, seed=0):
    """每个身份一组固定的正弦条纹纹理(模拟掌纹主线方向) + 逐样本噪声."""
    from PIL import Image

    if any(not isinstance(value, int) or isinstance(value, bool) or value <= 0
           for value in (num_class, per_class, size)):
        raise ValueError("num_class, per_class and size must be positive integers")
    g = torch.Generator().manual_seed(seed)
    yy, xx = torch.meshgrid(torch.linspace(0, 1, size), torch.linspace(0, 1, size), indexing="ij")
    images, labels = [], []
    for c in range(num_class):
        gc = torch.Generator().manual_seed(1000 + c)
        freq = 4 + 12 * torch.rand(3, generator=gc)
        phase = 2 * torch.pi * torch.rand(3, generator=gc)
        theta = torch.pi * torch.rand(3, generator=gc)
        base = torch.zeros(size, size)
        for k in range(3):
            proj = xx * torch.cos(theta[k]) + yy * torch.sin(theta[k])
            base = base + torch.sin(2 * torch.pi * freq[k] * proj + phase[k])
        base = (base - base.min()) / (base.max() - base.min() + 1e-8)
        for _ in range(per_class):
            img = (base + 0.05 * torch.randn(size, size, generator=g)).clamp(0, 1)
            images.append(Image.fromarray((img * 255).to(torch.uint8).numpy()))
            labels.append(c)
    return {"images": images, "labels": labels}


def train_victim(net_name, pth, num_class, epochs):
    class _A:
        pass

    a = _A()
    a.net, a.num_class = net_name, num_class
    net = get_net(a)
    ds = PalmPrint(data_dir=pth, norm="aug_0.5", train=True, co3net=False)
    dl = torch.utils.data.DataLoader(ds, batch_size=16, shuffle=True)
    opt = torch.optim.Adam(net.parameters(), lr=1e-3)
    for _ in range(epochs):
        net.train()
        for x, y in dl:
            logits = net(x, y) if net_name in ARC_NETS else net(x)
            loss = F.cross_entropy(logits, y)
            opt.zero_grad()
            loss.backward()
            opt.step()
    net.eval()
    test = PalmPrint(data_dir=pth, norm="aug_0.5", train=False, co3net=False)
    correct = 0
    with torch.no_grad():
        for x, y in torch.utils.data.DataLoader(test, batch_size=32):
            correct += (net(x).argmax(1) == y).sum().item()
    return net, correct / len(test)


def main(argv=None):
    p = argparse.ArgumentParser(description="Synthetic smoke data only; never paper evidence.")
    p.add_argument("--output-dir", required=True)
    p.add_argument("--train-victims", action="store_true",
                   help="explicitly opt in to victim training on this tool's own trusted synthetic data")
    p.add_argument("--nets", nargs="+", default=["compnet", "resnet18"],
                   choices=["vgg16", "resnet18", "mobilenetv2", "shufflenetv2", "compnet", "ccnet", "co3net"])
    p.add_argument("--num_class", type=int, default=8)
    p.add_argument("--epochs", type=int, default=15)
    args = p.parse_args(argv)
    if args.num_class <= 0:
        p.error("--num_class must be positive")
    if args.epochs < 0 or (args.train_victims and args.epochs <= 0):
        p.error("--epochs must be nonnegative, and positive with --train-victims")
    requested_out = Path(args.output_dir).expanduser()
    if requested_out.is_symlink():
        p.error(f"--output-dir already exists as a symlink: {requested_out}")
    out = requested_out.resolve()
    package_dir = Path(__file__).resolve().parents[1]
    if out == package_dir or package_dir in out.parents:
        p.error("--output-dir must not be inside the package directory")
    if out.exists():
        p.error(f"--output-dir already exists: {out}")
    out.mkdir(parents=True, exist_ok=False)
    (out / "data_pth").mkdir()
    metadata = {
        "schema": "synthetic-smoke",
        "evidence_type": "synthetic",
        "paper_eligible": False,
        "num_class": args.num_class,
        "train_victims": args.train_victims,
        "serialization": "legacy PIL pickle; load only when generated by a trusted source",
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    torch.manual_seed(0)
    pth = out / "data_pth" / "synth_128.pth"
    torch.save({"train": make_split(args.num_class, 10, seed=0),
                "test": make_split(args.num_class, 5, seed=1),
                "metadata": metadata}, pth)
    print(f"[synthetic data; not paper-eligible] {pth}")

    if args.train_victims:
        (out / "ckpt").mkdir()
        for name in args.nets:
            net, acc = train_victim(name, pth, args.num_class, args.epochs)
            ck = out / "ckpt" / f"{name}.pth"
            torch.save(net.state_dict(), ck)
            print(f"[synthetic ckpt] {name}: clean test acc = {acc:.3f} -> {ck}")


if __name__ == "__main__":
    main()
